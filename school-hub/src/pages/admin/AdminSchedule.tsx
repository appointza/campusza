type TimetableContext = {
  timeSlots: string[];
  gradePeriodByTime: Record<string, GradePeriod>;
  orderedGradePeriods: GradePeriod[];
  isBreakSlot: (time: string) => boolean;
  getBreakSlotLabel: (time: string) => string;
};

function buildTimetableContext(
  gradeId: string,
  gradePeriodsByGrade: Record<string, GradePeriod[]>,
  referenceValues: ReferenceValue[]
): TimetableContext {
  const orderedGradePeriods = [...(gradePeriodsByGrade[gradeId] || [])].sort(
    (a, b) => a.displayOrder - b.displayOrder
  );
  let timeSlots: string[];
  if (orderedGradePeriods.length > 0) {
    timeSlots = orderedGradePeriods.map((p) => formatTimeLabel(p.startTime));
  } else {
    const refs = getReferenceValuesByCategory(referenceValues, ReferenceValueCategory.PERIOD);
    timeSlots = refs.length === 0 ? DEFAULT_TIME_SLOTS : refs.map((r) => r.name);
  }
  const gradePeriodByTime = Object.fromEntries(
    orderedGradePeriods.map((p) => [formatTimeLabel(p.startTime), p])
  ) as Record<string, GradePeriod>;
  const isBreakSlot = (time: string) => {
    const period = gradePeriodByTime[time];
    return period ? isBreakPeriodCode(period.periodCode) : false;
  };
  const getBreakSlotLabel = (time: string) => gradePeriodByTime[time]?.periodName || "Break";
  return { timeSlots, gradePeriodByTime, orderedGradePeriods, isBreakSlot, getBreakSlotLabel };
}

type CompactTimetableGridProps = {
  timeSlots: string[];
  getScheduleForSlot: (day: string, time: string) => ScheduleEntry[];
  gradePeriodByTime: Record<string, GradePeriod>;
  isBreakSlot: (time: string) => boolean;
  getBreakSlotLabel: (time: string) => string;
  dayDateLabels?: Record<string, string>;
  replacementsForWeek?: Map<string, StaffReplacement>;
  weekRange?: WeekRange;
  interactive?: boolean;
  scrollable?: boolean;
  onEdit?: (item: ScheduleEntry, replacement?: StaffReplacement) => void;
  onDelete?: (id: string) => void;
  onAdd?: (day: string, time: string) => void;
};

function CompactTimetableGrid({
  timeSlots,
  getScheduleForSlot,
  gradePeriodByTime,
  isBreakSlot,
  getBreakSlotLabel,
  dayDateLabels,
  replacementsForWeek,
  weekRange,
  interactive = true,
  scrollable = true,
  onEdit,
  onDelete,
  onAdd,
}: CompactTimetableGridProps) {
  return (
    <div className="rounded-md border border-border overflow-hidden">
      <div className={scrollable ? "overflow-auto max-h-[calc(100vh-260px)]" : "overflow-x-auto"}>
        <div className="min-w-[720px]">
          <div className="grid grid-cols-8 gap-px bg-border sticky top-0 z-10">
            <div className="bg-muted px-1.5 py-1 text-[10px] font-medium text-muted-foreground flex items-center gap-1">
              <Clock className="w-3 h-3 shrink-0" />
              Slot
            </div>
            {days.map((day) => (
              <div
                key={day}
                className="bg-muted px-1 py-1 text-[10px] font-semibold text-center leading-tight"
                title={dayDateLabels?.[day] ? `${day} · ${dayDateLabels[day]}` : day}
              >
                <div>{dayShort[day]}</div>
                {dayDateLabels?.[day] ? (
                  <div className="text-[9px] font-normal text-muted-foreground mt-0.5">
                    {dayDateLabels[day]}
                  </div>
                ) : null}
              </div>
            ))}
          </div>

          {timeSlots.map((time) => {
            const isBreak = isBreakSlot(time);
            const period = gradePeriodByTime[time];
            return (
              <div key={time} className="grid grid-cols-8 gap-px bg-border">
                <div
                  className={`px-1.5 py-1 text-[10px] leading-tight flex flex-col justify-center bg-muted/40 ${
                    isBreak ? "text-amber-900 font-semibold" : "text-foreground"
                  }`}
                >
                  <span className="truncate">{period?.periodName || time}</span>
                  {period ? (
                    <span className="text-[9px] text-muted-foreground truncate">{time}</span>
                  ) : null}
                </div>
                {days.map((day) => {
                  const scheduleItems = getScheduleForSlot(day, time);
                  if (isBreak) {
                    return (
                      <div
                        key={`${day}-${time}`}
                        className="h-7 bg-amber-50 flex items-center justify-center text-[10px] font-medium text-amber-900 px-0.5"
                      >
                        <span className="truncate">{getBreakSlotLabel(time)}</span>
                      </div>
                    );
                  }
                  if (scheduleItems.length > 0) {
                    return (
                      <div key={`${day}-${time}`} className="h-11 p-0.5 bg-background">
                        {scheduleItems.map((item) => {
                          const replacement = weekRange && replacementsForWeek
                            ? getReplacementForScheduleOnDay(item.id, day, weekRange, replacementsForWeek)
                            : undefined;
                          const isReplacement = !!replacement;
                          return (
                            <div
                              key={item.id}
                              className={`h-full px-1 py-0.5 rounded ${item.color} ${
                                interactive ? "cursor-pointer hover:opacity-90 group relative" : ""
                              } ${isReplacement ? "ring-1 ring-yellow-500" : ""}`}
                              onClick={
                                interactive && onEdit
                                  ? () =>
                                      onEdit(
                                        {
                                          ...item,
                                          replacementTeacher:
                                            replacement?.replacementTeacherName || item.replacementTeacher,
                                          replacementTeacherId:
                                            replacement?.replacementTeacherId || item.replacementTeacherId,
                                          isReplacement,
                                        },
                                        replacement
                                      )
                                  : undefined
                              }
                              title={[item.subject, item.teacher, item.room].filter(Boolean).join(" · ")}
                            >
                              <div className="text-[10px] font-semibold leading-tight truncate">
                                {item.subject}
                              </div>
                              <div className="text-[9px] opacity-80 leading-tight truncate">
                                {isReplacement ? replacement?.replacementTeacherName : item.teacher}
                              </div>
                              {isReplacement && (
                                <Badge
                                  variant="outline"
                                  className="absolute -top-1 -right-1 h-3.5 px-1 text-[8px] bg-yellow-500 text-yellow-950 border-0"
                                >
                                  Sub
                                </Badge>
                              )}
                              {interactive && onDelete && (
                                <button
                                  type="button"
                                  className="absolute bottom-0 right-0 opacity-0 group-hover:opacity-100 p-0.5 hover:bg-destructive/20 rounded"
                                  onClick={(e) => {
                                    e.stopPropagation();
                                    onDelete(item.id);
                                  }}
                                >
                                  <Trash2 className="w-2.5 h-2.5 text-destructive" />
                                </button>
                              )}
                            </div>
                          );
                        })}
                      </div>
                    );
                  }
                  return (
                    <div
                      key={`${day}-${time}`}
                      className={`h-11 bg-muted/20 flex items-center justify-center ${
                        interactive ? "cursor-pointer hover:bg-muted/40" : ""
                      }`}
                      onClick={interactive && onAdd ? () => onAdd(day, time) : undefined}
                      title={interactive ? "Add schedule" : undefined}
                    >
                      {interactive ? <Plus className="w-3 h-3 text-muted-foreground" /> : null}
                    </div>
                  );
                })}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

