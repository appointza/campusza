import { useEffect, useMemo, useState } from "react";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Checkbox } from "@/components/ui/checkbox";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Badge } from "@/components/ui/badge";
import { Progress } from "@/components/ui/progress";
import { CheckCircle, AlertTriangle, Zap, RefreshCw } from "lucide-react";
import type { Class } from "@/models/class.model";
import type { GradePeriod } from "@/models/grade-period.model";
import type { ScheduleEntry, StaffLeave, StaffMember } from "@/models/staff.model";
import {
  classMatchesGradeRef,
  type ReferenceValue,
} from "@/models/referencevalue.model";
import type { AutoGenerateResult, AutoGenerateSettings, ScheduleViewMode } from "../types";
import {
  generateTimetable,
  getDefaultAutoGenerateSettings,
  getTeachingRowsForGrade,
} from "../utils/auto-generate-timetable";
import { gradePeriodsToRows } from "../utils/schedule-mapper";
import { ViewSwitcher } from "./ViewSwitcher";
import { ScheduleTimetableGrid } from "./ScheduleTimetableGrid";

type Props = {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  classes: Class[];
  grades: ReferenceValue[];
  staffMembers: StaffMember[];
  gradePeriodsByGrade: Record<string, GradePeriod[]>;
  existingSchedule: ScheduleEntry[];
  roomNames: string[];
  subjectOptions: ReferenceValue[];
  leaves: StaffLeave[];
  weekRange: { start: Date; end: Date };
  onApply: (result: AutoGenerateResult) => Promise<void>;
  busy?: boolean;
};

type Step = "configure" | "result" | "preview";

export function AutoGenerateDialog({
  open,
  onOpenChange,
  classes,
  grades,
  staffMembers,
  gradePeriodsByGrade,
  existingSchedule,
  roomNames,
  subjectOptions,
  leaves,
  weekRange,
  onApply,
  busy,
}: Props) {
  const [step, setStep] = useState<Step>("configure");
  const [settings, setSettings] = useState<AutoGenerateSettings>(() => getDefaultAutoGenerateSettings());
  const [result, setResult] = useState<AutoGenerateResult | null>(null);
  const [previewView, setPreviewView] = useState<ScheduleViewMode>("class");
  const [previewClassId, setPreviewClassId] = useState(classes[0]?.id || "");
  const [previewTeacherId, setPreviewTeacherId] = useState(staffMembers[0]?.id || "");
  const [previewRoom, setPreviewRoom] = useState(roomNames[0] || "");
  const [generating, setGenerating] = useState(false);

  useEffect(() => {
    if (open) {
      setStep("configure");
      setResult(null);
      setSettings(getDefaultAutoGenerateSettings());
      setPreviewClassId(classes[0]?.id || "");
    }
  }, [open, classes]);

  const classesForGrades = useMemo(() => {
    if (settings.selectedGradeIds.length === 0) return [];
    return classes.filter((c) =>
      settings.selectedGradeIds.some((gradeId) => classMatchesGradeRef(c.grade, gradeId, grades))
    );
  }, [classes, settings.selectedGradeIds, grades]);

  const toggleGrade = (gradeId: string, checked: boolean) => {
    setSettings((s) => {
      const gradeIds = checked
        ? [...new Set([...s.selectedGradeIds, gradeId])]
        : s.selectedGradeIds.filter((id) => id !== gradeId);
      const classIds = checked
        ? s.selectedClassIds
        : s.selectedClassIds.filter((id) => {
            const cls = classes.find((c) => c.id === id);
            if (!cls) return false;
            return !classMatchesGradeRef(cls.grade, gradeId, grades);
          });
      return { ...s, selectedGradeIds: gradeIds, selectedClassIds: classIds };
    });
  };

  const toggleClass = (classId: string, checked: boolean) => {
    setSettings((s) => ({
      ...s,
      selectedClassIds: checked
        ? [...new Set([...s.selectedClassIds, classId])]
        : s.selectedClassIds.filter((id) => id !== classId),
    }));
  };

  const runGenerate = (seed?: number) => {
    setGenerating(true);
    setTimeout(() => {
      const next = generateTimetable({
        classes,
        staffMembers,
        gradePeriodsByGrade,
        existingSchedule,
        roomNames,
        subjectOptions,
        leaves,
        weekRange,
        settings: { ...settings, seed: seed ?? Date.now() },
      });
      setResult(next);
      setStep("result");
      setGenerating(false);
    }, 50);
  };

  const previewEntries = useMemo(() => {
    if (!result) return [];
    return [...result.preserved, ...result.entries];
  }, [result]);

  const previewRows = useMemo(() => {
    if (previewView === "class" && previewClassId) {
      const cls = classes.find((c) => c.id === previewClassId);
      return cls ? getTeachingRowsForGrade(gradePeriodsByGrade, cls.grade) : [];
    }
    const allPeriods = Object.values(gradePeriodsByGrade).flat();
    return gradePeriodsToRows(allPeriods).filter((r) => !r.isBreak);
  }, [previewView, previewClassId, classes, gradePeriodsByGrade]);

  const getPreviewEntries = (day: string, timeLabel: string) =>
    previewEntries.filter((e) => {
      if (e.day !== day || e.time !== timeLabel) return false;
      if (previewView === "class") return e.classId === previewClassId;
      if (previewView === "teacher") return e.teacherId === previewTeacherId;
      if (previewView === "room") return e.room === previewRoom;
      return true;
    });

  const reset = () => {
    setStep("configure");
    setResult(null);
    setSettings(getDefaultAutoGenerateSettings());
  };

  const handleClose = (o: boolean) => {
    if (!o) reset();
    onOpenChange(o);
  };

  return (
    <Dialog open={open} onOpenChange={handleClose}>
      <DialogContent className="max-w-3xl max-h-[90vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <Zap className="h-5 w-5 text-amber-500" />
            Auto Generate Timetable
          </DialogTitle>
          <DialogDescription>
            Constraint-based generation using classes, subjects, staff, bell schedules, and rooms.
          </DialogDescription>
        </DialogHeader>

        {step === "configure" && (
          <div className="space-y-6 py-2">
            <div className="space-y-2">
              <Label>Generate for</Label>
              <Select
                value={settings.scope}
                onValueChange={(v) =>
                  setSettings((s) => ({ ...s, scope: v as AutoGenerateSettings["scope"] }))
                }
              >
                <SelectTrigger>
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="regular">Regular timetable</SelectItem>
                  <SelectItem value="week">Selected week</SelectItem>
                </SelectContent>
              </Select>
            </div>

            <div className="space-y-2">
              <Label>Grades</Label>
              <div className="grid gap-2 sm:grid-cols-2">
                {grades.map((g) => (
                  <label
                    key={g.id}
                    className="flex items-center gap-2 rounded-md border border-border/60 px-3 py-2 text-sm cursor-pointer"
                  >
                    <Checkbox
                      checked={settings.selectedGradeIds.includes(g.id)}
                      onCheckedChange={(c) => toggleGrade(g.id, c === true)}
                    />
                    {g.name}
                  </label>
                ))}
              </div>
            </div>

            <div className="space-y-2">
              <Label>Classes</Label>
              {settings.selectedGradeIds.length === 0 ? (
                <p className="text-sm text-muted-foreground">Select a grade above to see its classes.</p>
              ) : classesForGrades.length === 0 ? (
                <p className="text-sm text-muted-foreground">
                  No classes found for the selected grade(s). On Admin → Classes, set each class Grade to match
                  (e.g. UKG).
                </p>
              ) : (
                <div className="grid gap-2 sm:grid-cols-2 lg:grid-cols-3 max-h-40 overflow-y-auto">
                  {classesForGrades.map((c) => (
                    <label
                      key={c.id}
                      className="flex items-center gap-2 rounded-md border border-border/60 px-3 py-2 text-sm cursor-pointer"
                    >
                      <Checkbox
                        checked={settings.selectedClassIds.includes(c.id)}
                        onCheckedChange={(checked) => toggleClass(c.id, checked === true)}
                      />
                      {c.name}
                    </label>
                  ))}
                </div>
              )}
            </div>

            <div className="space-y-2 max-w-xs">
              <Label>Teacher workload</Label>
              <Select
                value={settings.workloadMode}
                onValueChange={(v) =>
                  setSettings((s) => ({ ...s, workloadMode: v as "balanced" | "priority" }))
                }
              >
                <SelectTrigger>
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="balanced">Balanced</SelectItem>
                  <SelectItem value="priority">Priority-based</SelectItem>
                </SelectContent>
              </Select>
            </div>

            <div className="grid gap-2 sm:grid-cols-2">
              {[
                ["balanceTeacherWorkload", "Balance teacher workload"],
                ["balanceFreePeriods", "Balance teacher free periods"],
                ["spreadSubjectsAcrossDays", "Spread subjects across days"],
                ["avoidRepeatedSubjects", "Avoid repeated subjects"],
                ["preserveLockedSchedules", "Preserve locked schedules"],
                ["avoidFirstLastRepetition", "Avoid first/last period repetition"],
                ["keepLabsConsecutive", "Keep labs as consecutive periods"],
                ["preferPeAfternoon", "Prefer PE in afternoon"],
                ["preferDifficultEarlier", "Prefer difficult subjects earlier"],
              ].map(([key, label]) => (
                <label key={key} className="flex items-center gap-2 text-sm">
                  <Checkbox
                    checked={settings[key as keyof AutoGenerateSettings] as boolean}
                    onCheckedChange={(c) =>
                      setSettings((s) => ({ ...s, [key]: c === true }))
                    }
                  />
                  {label}
                </label>
              ))}
            </div>
          </div>
        )}

        {step === "result" && result && (
          <div className="space-y-4 py-2">
            <div className="rounded-lg border border-border/60 p-4 space-y-3">
              <p className="font-medium flex items-center gap-2">
                <CheckCircle className="h-4 w-4 text-green-600" />
                Timetable generated successfully
              </p>
              <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-5 gap-2 text-sm">
                <div>
                  <span className="text-muted-foreground">Classes selected</span>
                  <p className="font-semibold">{result.stats.classes}</p>
                </div>
                <div>
                  <span className="text-muted-foreground">Classes generated</span>
                  <p className="font-semibold">{result.stats.classesGenerated}</p>
                </div>
                <div>
                  <span className="text-muted-foreground">Periods</span>
                  <p className="font-semibold">{result.stats.periodsGenerated}</p>
                </div>
                <div>
                  <span className="text-muted-foreground">Hard conflicts</span>
                  <p className="font-semibold">{result.stats.conflicts}</p>
                </div>
                <div>
                  <span className="text-muted-foreground">Partial placements</span>
                  <p className="font-semibold">{result.stats.unresolved}</p>
                </div>
              </div>
              {result.stats.perClass.length > 0 && (
                <div className="grid grid-cols-2 sm:grid-cols-3 gap-1 text-xs pt-1 border-t border-border/40">
                  {result.stats.perClass.map((c) => (
                    <span key={c.classId}>
                      {c.className}: <strong>{c.periodsGenerated}</strong> period
                      {c.periodsGenerated === 1 ? "" : "s"}
                    </span>
                  ))}
                </div>
              )}
            </div>

            <div className="space-y-2">
              <Label>Timetable validation</Label>
              <div className="space-y-1">
                {result.checks.map((c) => (
                  <div key={c.label} className="flex items-center gap-2 text-sm">
                    {c.ok ? (
                      <CheckCircle className="h-4 w-4 text-green-600 shrink-0" />
                    ) : (
                      <AlertTriangle className="h-4 w-4 text-amber-600 shrink-0" />
                    )}
                    {c.label}
                  </div>
                ))}
              </div>
            </div>

            {result.stats.conflicts === 0 && result.entries.length > 0 && (
              <p className="text-sm text-green-700 flex items-center gap-2">
                <CheckCircle className="h-4 w-4" />
                No hard conflicts — you can apply this timetable.
              </p>
            )}

            {result.unresolved.length > 0 && (
              <div className="rounded-lg border border-amber-500/40 bg-amber-500/10 p-3 space-y-1">
                <p className="text-sm font-medium flex items-center gap-2">
                  <AlertTriangle className="h-4 w-4" />
                  {result.stats.unresolved} subject period(s) could not be fully placed
                </p>
                {result.unresolved.slice(0, 5).map((u, i) => (
                  <p key={i} className="text-xs text-muted-foreground pl-6">
                    {i + 1}. {u.message}
                  </p>
                ))}
              </div>
            )}

            <div className="space-y-2">
              <div className="flex items-center justify-between">
                <Label>Overall timetable quality</Label>
                <Badge variant="secondary">{result.quality.overall}%</Badge>
              </div>
              <Progress value={result.quality.overall} className="h-2" />
              <div className="grid grid-cols-2 gap-2 text-xs text-muted-foreground">
                <span>Teacher balance: {result.quality.teacherBalance}%</span>
                <span>Subject distribution: {result.quality.subjectDistribution}%</span>
                <span>Room utilization: {result.quality.roomUtilization}%</span>
                <span>Free period balance: {result.quality.freePeriodBalance}%</span>
              </div>
            </div>

            {result.teacherWorkload.length > 0 && (
              <div className="space-y-1">
                <Label className="text-xs">Teacher workload</Label>
                <div className="grid grid-cols-2 sm:grid-cols-3 gap-1 text-xs">
                  {result.teacherWorkload.slice(0, 9).map((t) => (
                    <span key={t.teacherId}>
                      {t.name}: <strong>{t.periods}</strong>
                    </span>
                  ))}
                </div>
              </div>
            )}
          </div>
        )}

        {step === "preview" && result && (
          <div className="space-y-4 py-2">
            <ViewSwitcher value={previewView} onChange={setPreviewView} />
            {previewView === "class" && (
              <Select value={previewClassId} onValueChange={setPreviewClassId}>
                <SelectTrigger className="max-w-xs">
                  <SelectValue placeholder="Class" />
                </SelectTrigger>
                <SelectContent>
                  {classes
                    .filter((c) => settings.selectedClassIds.includes(c.id))
                    .map((c) => (
                      <SelectItem key={c.id} value={c.id}>
                        {c.name}
                      </SelectItem>
                    ))}
                </SelectContent>
              </Select>
            )}
            {previewView === "teacher" && (
              <Select value={previewTeacherId} onValueChange={setPreviewTeacherId}>
                <SelectTrigger className="max-w-xs">
                  <SelectValue placeholder="Teacher" />
                </SelectTrigger>
                <SelectContent>
                  {staffMembers.map((t) => (
                    <SelectItem key={t.id} value={t.id}>
                      {t.name}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            )}
            {previewView === "room" && (
              <Select value={previewRoom} onValueChange={setPreviewRoom}>
                <SelectTrigger className="max-w-xs">
                  <SelectValue placeholder="Room" />
                </SelectTrigger>
                <SelectContent>
                  {roomNames.map((r) => (
                    <SelectItem key={r} value={r}>
                      {r}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            )}
            <ScheduleTimetableGrid
              rows={previewRows}
              getEntries={getPreviewEntries}
              readOnly
              emptyMessage="No periods configured for this view."
            />
          </div>
        )}

        <DialogFooter className="flex-wrap gap-2">
          {step === "configure" && (
            <>
              <Button variant="outline" onClick={() => handleClose(false)}>
                Cancel
              </Button>
              <Button
                variant="hero"
                disabled={generating || settings.selectedClassIds.length === 0 || busy}
                onClick={() => runGenerate()}
              >
                <Zap className="h-4 w-4 mr-2" />
                {generating ? "Generating…" : "Generate"}
              </Button>
            </>
          )}
          {step === "result" && result && (
            <>
              <Button variant="outline" onClick={() => setStep("configure")}>
                Back
              </Button>
              <Button variant="outline" onClick={() => runGenerate(Date.now())}>
                <RefreshCw className="h-4 w-4 mr-2" />
                Regenerate
              </Button>
              <Button variant="outline" onClick={() => setStep("preview")}>
                Review Timetable
              </Button>
              <Button
                variant="hero"
                disabled={busy || result.entries.length === 0 || result.validation.conflicts.length > 0}
                onClick={() => void onApply(result)}
              >
                Apply Timetable
              </Button>
            </>
          )}
          {step === "preview" && (
            <>
              <Button variant="outline" onClick={() => setStep("result")}>
                Back to results
              </Button>
              <Button
                variant="hero"
                disabled={
                  busy ||
                  !result ||
                  result.entries.length === 0 ||
                  result.validation.conflicts.length > 0
                }
                onClick={() => result && void onApply(result)}
              >
                Apply Timetable
              </Button>
            </>
          )}
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
